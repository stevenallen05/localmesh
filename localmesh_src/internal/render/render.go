// Package render merges rendered plugin compose files into a single
// localmesh/bundled.compose.yaml per spec §2.5.
package render

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/stevenallen05/localmesh/internal/manifest"
	tmpl "github.com/stevenallen05/localmesh/internal/template"
)

// Run renders every plugin in catalogRoot and writes the merged output
// to outputPath. projectFile is the path to project.toml. Returns an
// error with context on the first failure.
func Run(projectFile, catalogRoot, outputPath string) error {
	// deploy.toml is consumed by envwriter, not render — discard the Deploy.
	proj, plugins, _, err := manifest.LoadAll(projectFile, catalogRoot)
	if err != nil {
		return err
	}
	return RunWith(proj, plugins, catalogRoot, outputPath)
}

// RunWith is Run with already-loaded manifests. Lets callers (the build verb)
// load once and pass the same structs to render + envwriter.
//
// Single pass: the meshed-workload set is known from the manifests before any
// template runs (needs_mtls_sidecar lives in [[services]], not in compose), so
// every plugin is rendered once with the full ServiceCtx list in its context.
// The security plugin iterates it to emit sidecars + ingress routes; other
// plugins ignore it.
func RunWith(proj *manifest.Project, plugins []*manifest.Plugin, catalogRoot, outputPath string) error {
	env := envMap()
	outputDir := filepath.Dir(outputPath)
	services, err := serviceList(proj, plugins)
	if err != nil {
		return err
	}
	rendered := make([]*yaml.Node, 0, len(plugins))
	sources := make([]string, 0, len(plugins))
	for _, p := range plugins {
		node, err := renderPluginCompose(proj, p, env, services, catalogRoot, outputDir)
		if err != nil {
			return err
		}
		rendered = append(rendered, node)
		sources = append(sources, p.Name)
	}
	merged, err := Merge(rendered, sources)
	if err != nil {
		return err
	}
	if err := SortServices(merged); err != nil {
		return err
	}
	out, err := yaml.Marshal(merged)
	if err != nil {
		return fmt.Errorf("marshal merged: %w", err)
	}
	header := "# Auto-generated by ./localmesh_src/cmd/localmesh build — do not edit by hand.\n"
	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", filepath.Dir(outputPath), err)
	}
	return os.WriteFile(outputPath, append([]byte(header), out...), 0o644)
}

// serviceList collects every registry-known service (project [[services]] +
// every plugin [[services]]) into the template context shape. Project services
// first (slug "app"), then plugins in load order (slug = plugin name); deduped
// by container (first wins); sorted by name for deterministic output. Returns
// an error if any service's scheme has no kuma.io/protocol mapping.
func serviceList(proj *manifest.Project, plugins []*manifest.Plugin) ([]tmpl.ServiceCtx, error) {
	seen := map[string]bool{}
	out := []tmpl.ServiceCtx{}
	add := func(s manifest.Service, pluginSlug string) error {
		if seen[s.Container] {
			return nil
		}
		seen[s.Container] = true
		protocol, err := tmpl.SchemeProtocol(s.Scheme)
		if err != nil {
			return fmt.Errorf("plugin %q service %q: %w", pluginSlug, s.Container, err)
		}
		out = append(out, tmpl.ServiceCtx{
			Name:             s.Container,
			Port:             s.Port,
			Protocol:         protocol,
			Plugin:           pluginSlug,
			ExposeViaIngress: s.ExposeViaIngress,
		})
		return nil
	}
	for _, s := range proj.Services {
		if err := add(s, "app"); err != nil {
			return nil, err
		}
	}
	for _, p := range plugins {
		for _, s := range p.Services {
			if err := add(s, p.Name); err != nil {
				return nil, err
			}
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// renderPluginCompose renders one plugin's docker-compose template + parses
// the output + rewrites relative paths.
func renderPluginCompose(proj *manifest.Project, p *manifest.Plugin, env map[string]string, services []tmpl.ServiceCtx, catalogRoot, outputDir string) (*yaml.Node, error) {
	composePath := pluginComposePath(catalogRoot, p.Name)
	ctx := &tmpl.Context{Project: proj, Plugin: p, Env: env, Services: services}
	body, err := tmpl.Render(composePath, ctx)
	if err != nil {
		return nil, err
	}
	var node yaml.Node
	if err := yaml.Unmarshal(body, &node); err != nil {
		return nil, fmt.Errorf("parse rendered %s: %w", composePath, err)
	}
	// Relative paths inside each plugin's compose are authored relative
	// to that plugin's dir; rewrite them so they resolve from the merged
	// output's dir instead. Both sides absolutized so filepath.Rel works
	// even when callers pass relative paths.
	absOut, err := filepath.Abs(outputDir)
	if err != nil {
		return nil, fmt.Errorf("abs %s: %w", outputDir, err)
	}
	absPlugin, err := filepath.Abs(filepath.Dir(composePath))
	if err != nil {
		return nil, fmt.Errorf("abs %s: %w", composePath, err)
	}
	relPrefix, err := filepath.Rel(absOut, absPlugin)
	if err != nil {
		return nil, fmt.Errorf("rel path %s -> %s: %w", absOut, absPlugin, err)
	}
	RewriteRelativePaths(&node, relPrefix)
	return &node, nil
}

func pluginComposePath(catalogRoot, name string) string {
	candidates := []string{
		filepath.Join(catalogRoot, name, "docker-compose.yaml.gotmpl"),
		filepath.Join(catalogRoot, name, "docker-compose.yml.gotmpl"),
		filepath.Join(catalogRoot, name, "docker-compose.yaml"),
		filepath.Join(catalogRoot, name, "docker-compose.yml"),
	}
	for _, p := range candidates {
		if _, err := os.Stat(p); err == nil {
			return p
		}
	}
	// Return the last candidate — the read will fail with a clear error.
	return candidates[len(candidates)-1]
}

func envMap() map[string]string {
	env := os.Environ()
	out := make(map[string]string, len(env))
	for _, e := range env {
		if k, v, ok := strings.Cut(e, "="); ok {
			out[k] = v
		}
	}
	return out
}

// SortServices reorders services.<X> keys alphabetically (spec §2.5).
func SortServices(root *yaml.Node) error {
	if root.Kind != yaml.DocumentNode || len(root.Content) == 0 {
		return nil
	}
	top := root.Content[0]
	if top.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i < len(top.Content); i += 2 {
		k := top.Content[i]
		v := top.Content[i+1]
		if k.Value == "services" && v.Kind == yaml.MappingNode {
			sortMappingKeys(v)
		}
	}
	return nil
}

func sortMappingKeys(m *yaml.Node) {
	type kv struct{ k, v *yaml.Node }
	pairs := make([]kv, 0, len(m.Content)/2)
	for i := 0; i < len(m.Content); i += 2 {
		pairs = append(pairs, kv{m.Content[i], m.Content[i+1]})
	}
	sort.Slice(pairs, func(i, j int) bool { return pairs[i].k.Value < pairs[j].k.Value })
	m.Content = m.Content[:0]
	for _, p := range pairs {
		m.Content = append(m.Content, p.k, p.v)
	}
}
